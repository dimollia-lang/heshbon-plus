def write(path, text):
    full = os.path.join(ROOT, path)
    d = os.path.dirname(full)
    if d and not os.path.isdir(d):
        os.makedirs(d)
    io.open(full, "w", encoding="utf-8", newline="\n").write(text)
    print("written:", path)

