def money(x, d=0):
    s = "%.*f" % (d, x)
    whole, frac = (s.split(".") + [""])[:2]
    out = ""
    while len(whole) > 3:
        out = u" " + whole[-3:] + out
        whole = whole[:-3]
    return whole + out + ((u"," + frac) if frac else u"")

def pct(x, d=2):
    s = "%.*f" % (d, x * 100)
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    return s.replace(".", ",")

